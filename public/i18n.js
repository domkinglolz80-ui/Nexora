// Translates a text from the code. Values in {braces} are filled in from `vars`.
function t(text, vars) {
  let out = (LANG === 'en' && EN[text]) || text;
  if (vars) out = out.replace(/\{(\w+)\}/g, (whole, key) => (key in vars ? String(vars[key]) : whole));
  return out;
}

// Translates a message that came from the server (it is always German).
function tServer(text) {
  if (LANG !== 'en' || typeof text !== 'string') return text;
  if (EN[text]) return EN[text];
  for (const [re, replacement] of EN_PATTERNS) {
    if (re.test(text)) return text.replace(re, replacement);
  }
  return text;
}

const numberFmt = new Intl.NumberFormat(LOCALE);

// "1 Hub", "3 Hubs" – both forms are translated.
function plural(n, one, many) {
  return `${numberFmt.format(n)} ${t(n === 1 ? one : many)}`;
}

// "1,5" in German, "1.5" in English.
function decimal(value) {
  return LANG === 'de' ? String(value).replace('.', ',') : String(value);
}

function setLanguage(lang) {
  if (lang === LANG || !LANGS.some((l) => l.id === lang)) return;
  try {
    localStorage.setItem('nexora:lang', JSON.stringify(lang));
  } catch {
    /* storage not available – the language then only changes for this visit */
  }
  location.reload();
}

// The static page (index.html) is written in German; translate its texts and hints in place.
function translatePage(root = document.body) {
  if (LANG === 'de') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (text && EN[text]) node.nodeValue = node.nodeValue.replace(text, EN[text]);
  }
  for (const el of root.querySelectorAll('[title], [placeholder], [aria-label]')) {
    for (const attr of ['title', 'placeholder', 'aria-label']) {
      const value = el.getAttribute(attr);
      if (value && EN[value]) el.setAttribute(attr, EN[value]);
    }
  }
}

translatePage();

